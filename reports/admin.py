"""Report type and branch report administration (SRS 29)."""

from django.contrib import admin

from .models import BranchReport, ReportType


@admin.register(ReportType)
class ReportTypeAdmin(admin.ModelAdmin):
    list_display = (
        'code', 'name', 'frequency', 'deadline_day', 'requires_financial_summary', 'is_active',
    )
    list_filter = ('frequency', 'is_active', 'requires_financial_summary')
    search_fields = ('code', 'name', 'name_sw', 'description')


@admin.register(BranchReport)
class BranchReportAdmin(admin.ModelAdmin):
    list_display = (
        'report_number', 'branch', 'report_type', 'period_label', 'status', 'submitted_at', 'reviewed_at',
    )
    list_filter = ('status', 'report_type', 'branch', 'period_year')
    search_fields = ('report_number', 'period_label', 'branch__name', 'achievements', 'challenges')
    # report_number is generated by the platform.
    readonly_fields = ('report_number', 'created_at', 'updated_at')
    autocomplete_fields = ('report_type', 'branch', 'submitted_by', 'reviewed_by')
