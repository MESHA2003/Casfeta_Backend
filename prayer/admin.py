"""Prayer request administration (SRS 30)."""

from django.contrib import admin

from .models import PrayerFollowUp, PrayerRequest


class PrayerFollowUpInline(admin.TabularInline):
    model = PrayerFollowUp
    extra = 0
    autocomplete_fields = ('handled_by',)


@admin.register(PrayerRequest)
class PrayerRequestAdmin(admin.ModelAdmin):
    list_display = (
        'reference', 'subject', 'category', 'branch', 'status', 'is_private', 'assigned_to', 'created_at',
    )
    list_filter = ('status', 'category', 'is_private', 'branch')
    search_fields = ('reference', 'subject', 'details', 'follow_up_notes', 'answered_note')
    # reference is generated by the platform.
    readonly_fields = ('reference', 'created_at', 'updated_at')
    autocomplete_fields = ('member', 'user', 'branch', 'assigned_to')
    inlines = [PrayerFollowUpInline]


@admin.register(PrayerFollowUp)
class PrayerFollowUpAdmin(admin.ModelAdmin):
    list_display = ('prayer_request', 'handled_by', 'is_private', 'created_at')
    list_filter = ('is_private', 'created_at')
    search_fields = ('prayer_request__reference', 'prayer_request__subject', 'note')
    autocomplete_fields = ('prayer_request', 'handled_by')
