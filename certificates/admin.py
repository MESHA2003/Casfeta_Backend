"""Certificate template and certificate administration (SRS 28)."""

from django.contrib import admin

from .models import Certificate, CertificateTemplate


@admin.register(CertificateTemplate)
class CertificateTemplateAdmin(admin.ModelAdmin):
    list_display = ('name', 'title', 'issuer_name', 'is_active', 'updated_at')
    list_filter = ('is_active',)
    search_fields = ('name', 'title', 'issuer_name')


@admin.register(Certificate)
class CertificateAdmin(admin.ModelAdmin):
    list_display = (
        'certificate_id', 'recipient_name', 'certificate_type', 'status',
        'issued_date', 'verification_count',
    )
    list_filter = ('certificate_type', 'status', 'issued_date')
    search_fields = ('certificate_id', 'recipient_name', 'programme', 'issuer_name')
    date_hierarchy = 'issued_date'
    # certificate_id, qr_token and the verification counter are generated by
    # the platform and must not be edited by hand.
    readonly_fields = ('certificate_id', 'qr_token', 'verification_count', 'created_at', 'updated_at')
    autocomplete_fields = ('recipient_member', 'recipient_user', 'issued_by', 'template')
