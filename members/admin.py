"""Member, membership application and transfer administration (SRS 19-21)."""

from django.contrib import admin

from core.admin import SoftDeleteAdmin

from .models import Member, MemberTransfer, MembershipApplication


@admin.register(MembershipApplication)
class MembershipApplicationAdmin(admin.ModelAdmin):
    list_display = (
        'application_number', 'first_name', 'last_name', 'branch', 'status', 'reviewed_by', 'created_at',
    )
    list_filter = ('status', 'branch', 'created_at')
    search_fields = (
        'application_number', 'first_name', 'last_name', 'email', 'phone', 'course_programme',
    )
    # application_number is generated in MembershipApplication.save().
    readonly_fields = ('application_number', 'created_at', 'updated_at')
    autocomplete_fields = ('user', 'branch', 'district', 'institution', 'reviewed_by', 'created_member')


@admin.register(Member)
class MemberAdmin(SoftDeleteAdmin):
    list_display = (
        'member_id', 'first_name', 'last_name', 'branch', 'status', 'phone', 'membership_start_date',
    )
    list_filter = ('status', 'gender', 'branch', 'is_baptised', 'is_active')
    search_fields = (
        'member_id', 'first_name', 'last_name', 'other_names', 'email', 'phone', 'national_id',
    )
    # member_id and qr_token are generated by the platform.
    readonly_fields = ('member_id', 'qr_token', 'card_issued_at', 'created_at', 'updated_at')
    autocomplete_fields = ('user', 'branch', 'institution', 'academic_year', 'district', 'approved_by')


@admin.register(MemberTransfer)
class MemberTransferAdmin(admin.ModelAdmin):
    list_display = (
        'member', 'from_branch', 'to_branch', 'status', 'requested_by', 'approved_at', 'completed_at',
    )
    list_filter = ('status', 'from_branch', 'to_branch')
    search_fields = ('member__first_name', 'member__last_name', 'member__member_id', 'reason')
    autocomplete_fields = ('member', 'from_branch', 'to_branch', 'requested_by', 'approved_by')
